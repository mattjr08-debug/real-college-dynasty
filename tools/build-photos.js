// Builds src/js/0000e-RealPhotos.js: an index of the player photos the user supplied (realdata/photos-128/<School>/<Player>.jpg, listed in the roster CSV).
// The images are not embedded: they sit in a "photos" folder next to the game file (tools/make-real-app.sh copies them there).
// A player gets his photo through his face seed: seeds from 1,000,000,000 up mean "photo number N" (see REAL_PHOTO_SEED / REAL_PHOTO_PATH). The seed is saved with the player,
// so the photo follows him through transfers and the draft. Matching is by school AND name, so two players with the same name never swap photos.
// Usage: node tools/build-photos.js   (then node tools/apply-real.js && node tools/build.js)
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..'), SRC = path.join(ROOT, 'realdata/photos-src'), PH = path.join(ROOT, 'realdata/photos-128');
const csv = fs.readFileSync(path.join(SRC, 'Roster list 2026-27.csv'), 'utf8').replace(/^﻿/, '').trim().split('\n').map(l => { const o = []; let c = '', q = false; for (const ch of l.replace(/\r$/, '')) { if (ch === '"') q = !q; else if (ch === ',' && !q) { o.push(c); c = ''; } else c += ch; } o.push(c); return o; });
const strip = s => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '');
const key = n => strip(n).toLowerCase().replace(/\b(jr|sr|ii|iii|iv|v)\b\.?/g, '').replace(/[^a-z]/g, '');
const nrm = s => strip(s).toLowerCase().replace(/&/g, ' and ').replace(/[.'’]/g, '').replace(/[^a-z0-9]+/g, ' ').replace(/\bsaint\b/g, 'st').replace(/\bstate\b/g, 'st').replace(/\s+/g, ' ').trim();
// the game's school names
const names = []; for (const l of fs.readFileSync(path.join(ROOT, 'data/real-schools.final.txt'), 'utf8').trim().split('\n')) if (l[0] !== '#') names.push(l.split('|')[0]);
const ALIAS = { 'Hawaii': "Hawai'i", 'Connecticut': 'UConn', 'Massachusetts': 'UMass', 'Miami FL': 'Miami', 'Miami OH': 'Miami (OH)', 'Saint Francis': 'Saint Francis (PA)', 'CSU Bakersfield': 'Cal State Bakersfield' };
const byNorm = {}; names.forEach(n => (byNorm[nrm(n)] = n));
const gameName = s => byNorm[nrm(s)] || ALIAS[s] || null;
const list = [], by = {}; let missing = 0, none = 0; const unknownSchools = new Set();
for (const r of csv.slice(1)) {
  const [, school, player, , , , , file] = r;
  if (!file) { none++; continue; }
  if (!fs.existsSync(path.join(PH, file))) { missing++; continue; }
  const g = gameName(school);
  if (!g) { unknownSchools.add(school); continue; }
  const k = g + '|' + key(player);
  if (by[k] != null) continue;
  by[k] = list.length;
  list.push(file.split('/').map(encodeURIComponent).join('/'));
}
// real starting-portal players (realdata/photos-128/_portal/<Player>.jpg), looked up with school "_portal"
const PDIR = path.join(PH, '_portal');
if (fs.existsSync(PDIR)) for (const f of fs.readdirSync(PDIR).sort()) { if (!/\.jpg$/i.test(f)) continue; const k = '_portal|' + key(f.replace(/\.jpg$/i, '')); if (by[k] != null) continue; by[k] = list.length; list.push(['_portal', f].map(encodeURIComponent).join('/')); }
const js = '// Player photos supplied by the user (personal copy). An index only: the images are in the "photos" folder next to the game. Generated by tools/build-photos.js.\n' +
  'var REAL_PHOTO_LIST = ' + JSON.stringify(list) + ';\n' +
  'var REAL_PHOTO_BY = ' + JSON.stringify(by) + ';\n' +
  'function REAL_PHOTO_SEED(name, school) {\n' +
  '  var k = String(name || "").normalize("NFD").replace(/[\\u0300-\\u036f]/g, "").toLowerCase().replace(/\\b(jr|sr|ii|iii|iv|v)\\b\\.?/g, "").replace(/[^a-z]/g, ""), i = REAL_PHOTO_BY[school + "|" + k];\n' +
  '  return i == null ? 0 : 1000000000 + i;\n' +
  '}\n' +
  'var REAL_PHOTO_SPRITE = ' + (process.env.SPRITE ? fs.readFileSync(path.join(ROOT, 'realdata/sprites/layout.json'), 'utf8') : 'null') + ';\n' +
  '// desktop app: a file in the photos folder; web/phone build: a cell in a sprite sheet (photos-N.jpg next to the page)\n' +
  'function REAL_PHOTO_PATH(seed) {\n' +
  '  if (!(seed >= 1000000000 && seed < 1000000000 + REAL_PHOTO_LIST.length)) return null;\n' +
  '  var i = seed - 1000000000, L = REAL_PHOTO_SPRITE;\n' +
  '  if (!L) return "photos/" + REAL_PHOTO_LIST[i];\n' +
  '  var k = i % L.per;\n' +
  '  return { url: "photos-" + Math.floor(i / L.per) + ".jpg", x: ((k % L.cols) / (L.cols - 1)) * 100, y: (Math.floor(k / L.cols) / (L.rows - 1)) * 100, w: L.cols * 100, h: L.rows * 100 };\n' +
  '}\n';
fs.writeFileSync(path.join(ROOT, 'src/js/0000e-RealPhotos.js'), js);
console.log('indexed', list.length, 'photos; roster rows with no photo file:', missing + none, '; schools not recognised:', [...unknownSchools]);
