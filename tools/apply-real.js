function patch(file, fn) { const p = J(file); let s = fs.readFileSync(p, 'utf8'); const out = fn(s); if (out !== s) fs.writeFileSync(p, out); }
function rep1(s, a, b, label) { const i = s.indexOf(a); if (i < 0) { if (s.includes('REAL_')) return s; throw new Error('patch target not found: ' + label); } if (s.indexOf(a, i + 1) >= 0) throw new Error('patch target not unique: ' + label); return s.replace(a, () => b); }
function arrEnd(s, from) { let d = 0, i = s.indexOf('[', from); for (; i < s.length; i++) { if (s[i] === '[') d++; else if (s[i] === ']') { d--; if (!d) return i; } } throw new Error('no end'); }

