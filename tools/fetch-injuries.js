// Fetches real-life injuries for every player on a 2026-27 ESPN roster and writes src/js/0000g-RealInjuries.js.
// Usage (needs internet; run on the Mac): node tools/fetch-injuries.js   then   node tools/build.js
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..'), dir = path.join(ROOT, 'realdata/espn-rosters');
const ids = [];
for (const f of fs.readdirSync(dir)) { try { const d = JSON.parse(fs.readFileSync(path.join(dir, f))); for (const a of d.athletes || []) ids.push({ id: a.id, n: a.fullName, team: (d.team && (d.team.location || d.team.displayName)) || '' }); } catch (e) {} }
const out = []; let i = 0;
const games = (x) => {
  const s = JSON.stringify(x).toLowerCase();
  if (/season|indefinite/.test(s)) return 30;
  const rd = x.details && x.details.returnDate || x.returnDate;
  if (rd) { const days = (new Date(rd) - Date.now()) / 864e5; if (days > 0) return Math.max(1, Math.round(days * 0.36)); }
  if (/day-to-day|questionable|probable/.test(s)) return 2;
  return 6;
};
const label = (x) => (x.details && (x.details.type || x.details.detail)) || (x.type && (x.type.description || x.type.text)) || x.shortComment || 'Injury';
async function worker() {
  while (i < ids.length) {
    const a = ids[i++];
    try {
      const r = await fetch(`https://sports.core.api.espn.com/v2/sports/basketball/leagues/mens-college-basketball/seasons/2027/athletes/${a.id}/injuries`, { headers: { 'User-Agent': 'Mozilla/5.0' } });
      if (!r.ok) continue; const j = await r.json();
      for (let it of j.items || []) { if (it.$ref) { try { it = await (await fetch(it.$ref.replace('http:', 'https:'))).json(); } catch (e) { continue; } } out.push([a.n, a.team, String(label(it)), games(it)]); }
    } catch (e) {}
  }
}
Promise.all(Array.from({ length: 8 }, worker)).then(() => {
  fs.writeFileSync(path.join(ROOT, 'src/js/0000g-RealInjuries.js'), '// REAL COLLEGE DYNASTY: players hurt in real life when fetched: [name, school, injury, games out]. Generated by tools/fetch-injuries.js.\nvar REAL_INJURIES = ' + JSON.stringify(out) + ';\n');
  console.log('players checked', ids.length, 'injured', out.length);
});
