// Packs the logo images the user supplied (realdata/logos-96/<School>.png, 112px) into src/js/0000d-RealLogos.js as data URIs, keyed by school name.
// Usage: node tools/build-logos.js   (then node tools/apply-real.js && node tools/build.js)
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..'), DIR = path.join(ROOT, 'realdata/logos-96');
const norm = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/[.'’]/g, '').replace(/[^a-z0-9]+/g, ' ').replace(/\bsaint\b/g, 'st').replace(/\bstate\b/g, 'st').replace(/\s+/g, ' ').trim();
const files = fs.readdirSync(DIR).filter(f => f.endsWith('.png'));
const byNorm = {}; files.forEach(f => (byNorm[norm(f.replace(/\.png$/, ''))] = f));
const schools = []; for (const l of fs.readFileSync(path.join(ROOT, 'data/real-schools.final.txt'), 'utf8').trim().split('\n')) if (l[0] !== '#') schools.push(l.split('|')[0]);
const ALIAS = { "Hawai'i": 'Hawaii', 'UConn': 'Connecticut', 'UMass': 'Massachusetts', 'Miami': 'Miami FL', 'Miami (OH)': 'Miami OH', 'Saint Francis (PA)': 'Saint Francis', 'Cal State Bakersfield': 'CSU Bakersfield' };
const used = new Set(), miss = [], out = {};
for (const s of schools) {
  let f = byNorm[norm(s)] || (ALIAS[s] && byNorm[norm(ALIAS[s])]);
  if (!f) { miss.push(s); continue; }
  used.add(f); out[s] = 'data:image/png;base64,' + fs.readFileSync(path.join(DIR, f)).toString('base64');
}
const left = files.filter(f => !used.has(f));
console.log('matched', Object.keys(out).length, 'of', schools.length, '\nschools without a file:', miss, '\nfiles not used:', left);
fs.writeFileSync(path.join(ROOT, 'src/js/0000d-RealLogos.js'), '// Logo images supplied by the user (personal copy), one per school, keyed by school name. Generated by tools/build-logos.js.\nvar REAL_LOGOS = ' + JSON.stringify(out) + ';\n');
